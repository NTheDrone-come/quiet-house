export const SEARCH_OBJECTS=rows.filter(([id])=>searchIds.has(id)).map(([id,x,floor,name,kind,contents,text])=>({id,x,floor,name,kind,contents:contents.split('|'),text}));

// Shuffle a fresh copy once per attempt, never on opening/closing an inspection.
// Separate homes keep a scare from blocking the only copy of a consumable.
export function createSearchObjects(random=Math.random,day=1){
 const objects=SEARCH_OBJECTS.map(o=>({...o,contents:[...o.contents],item:null,spider:false}));
 const homes=[...objects];
 for(let i=homes.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[homes[i],homes[j]]=[homes[j],homes[i]];}
 Object.keys(ITEMS).forEach((id,i)=>{homes[i].item=id;});
 const spiderCount=day===1?2:day===2?4:5;
 for(let i=Object.keys(ITEMS).length;i<Object.keys(ITEMS).length+spiderCount;i++)homes[i].spider=true;
 // Six separate caches guarantee enough for the full protection kit in one thorough search.
 [30,40,50,30,60,70].forEach((amount,i)=>{homes[Object.keys(ITEMS).length+spiderCount+i].money=amount;});
 return objects;
}
